#!/usr/bin/env python3
"""Regenerates Sources/DottieKit/PlayerScript.swift: dottie.js's <dottie-player> runtime and the loader that
follows it in a compiled drawing, so `dottie render -f js` writes what `dottie-compile` (npm) writes. Reads the
built files in web/dist; run through `just player-script`, which builds them first. --check fails instead of
writing when the Swift file is out of date (CI runs it after building web/).
"""
import base64, json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
dist = root / "web" / "dist"
out = root / "Sources" / "DottieKit" / "PlayerScript.swift"


def literal(text: str) -> str:
    hashes = "#"
    while f'"{hashes}' in text or f'{hashes}"' in text.replace('"""', ""):
        hashes += "#"
    return f'{hashes}"""\n{text}\n"""{hashes}'


runtime = (dist / "dottie-player.min.js").read_text().rstrip("\n")
loader = (dist / "dottie-loader.js").read_text().rstrip("\n")
simulation = (dist / "dottie-sim.min.js").read_text().rstrip("\n")
# Base64: the engine's minified source holds bytes Swift won't take in a string literal.
logic = base64.b64encode((dist / "dottie-logic.min.js").read_bytes()).decode()
version = json.loads((root / "web" / "package.json").read_text())["version"]
swift = f"""// Generated by scripts/update-player-script.py from web/dist; do not edit.

import Foundation

/// dottie.js's <dottie-player> runtime (dist/dottie-player.min.js) and the loader that follows it in a compiled
/// drawing (see `Exporter.script` and web/src/compile.ts).
enum PlayerScript {{
    static let version = "{version}"
    static let runtime = {literal(runtime)}
    static let loader = {literal(loader)}
    /// The simulation DottieKit runs in JavaScriptCore (dist/dottie-sim.min.js, `SimulationEngine`).
    static let simulation = {literal(simulation)}
    /// The click-logic engine (dist/dottie-logic.min.js, `LogicEngine`, ADR 0007): QuickJS in WebAssembly, as base64.
    static let logicBase64 = "{logic}"
    static var logic: String {{ String(decoding: Data(base64Encoded: logicBase64) ?? Data(), as: UTF8.self) }}
}}
"""
if "--check" in sys.argv:
    if not out.exists() or out.read_text() != swift:
        sys.exit("Sources/DottieKit/PlayerScript.swift is out of date with web/: run just player-script and commit it.")
    print("PlayerScript.swift is up to date")
else:
    out.write_text(swift)
    print("wrote", out.relative_to(root), f"({len(swift) // 1024} KB)")
