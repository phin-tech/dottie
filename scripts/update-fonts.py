#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["fonttools==4.60.1", "brotli==1.1.0"]
# ///
"""Regenerates the handwriting fonts Dottie bundles: web/fonts/*.woff2 (what dottie.js serves next to the
player), web/fonts/OFL-*.txt (their licenses) and Sources/DottieKit/BundledFonts.swift (the same files, embedded,
so the app, `dottie` and `dottie-mcp` need no resource bundle).

Each font comes from google/fonts at a pinned commit, under the SIL Open Font License. Variable fonts are cut
into fixed regular, bold and italic faces; every face keeps only Latin text and the symbols Dottie's labels and
notes use, and only kerning among its layout features, so a character's width doesn't depend on its neighbours
beyond the kerning pairs dottie.js measures (scripts/font-metrics.swift). Run `swift scripts/font-metrics.swift`
afterwards. Change COMMIT or FONTS here and rerun to update.
"""
import base64, io, pathlib, urllib.parse, urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

COMMIT = "47d54ca1ebb14fd864695f1d39dc734f39017c33"

# family -> (directory in google/fonts, {face: (file, axis locations)})
FONTS = {
    "Caveat": ("ofl/caveat", {
        "regular": ("Caveat[wght].ttf", {"wght": 400}),
        "bold": ("Caveat[wght].ttf", {"wght": 700}),
    }),
    "Patrick Hand": ("ofl/patrickhand", {"regular": ("PatrickHand-Regular.ttf", None)}),
    "Architects Daughter": ("ofl/architectsdaughter", {"regular": ("ArchitectsDaughter-Regular.ttf", None)}),
}

# Basic Latin, Latin-1, Latin Extended-A, general punctuation, the euro, and the symbols notes draw
# (bullets, arrows, check boxes), where the font has them.
UNICODES = [*range(0x20, 0x7F), *range(0xA0, 0x180), *range(0x2010, 0x2028), *range(0x2030, 0x203B), 0x20AC,
            *range(0x2190, 0x2194), 0x2022, 0x25E6, 0x2610, 0x2611, 0x2713]

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "fonts"


def fetch(directory: str, name: str) -> bytes:
    url = f"https://raw.githubusercontent.com/google/fonts/{COMMIT}/{directory}/{urllib.parse.quote(name)}"
    with urllib.request.urlopen(url) as r:
        return r.read()


def slug(family: str) -> str:
    return family.lower().replace(" ", "-")


def face(raw: bytes, location: dict | None, family: str, face: str) -> bytes:
    font = TTFont(io.BytesIO(raw))
    if location is not None:
        font = instancer.instantiateVariableFont(font, location)
    bold, italic = face in ("bold", "boldItalic"), face in ("italic", "boldItalic")
    # What CoreText reads a face's traits from, set plainly rather than trusting each source's names.
    font["OS/2"].usWeightClass = 700 if bold else 400
    sel = font["OS/2"].fsSelection & ~0b1100001  # clear italic, bold, regular
    font["OS/2"].fsSelection = sel | (1 if italic else 0) | (0b100000 if bold else 0) | (0 if bold or italic else 0b1000000)
    font["head"].macStyle = (1 if bold else 0) | (2 if italic else 0)
    style = {"regular": "Regular", "bold": "Bold", "italic": "Italic", "boldItalic": "Bold Italic"}[face]
    names = font["name"]
    for rec in list(names.names):
        if rec.nameID in (16, 17, 21, 22, 25):
            names.removeNames(nameID=rec.nameID)
    for pid, eid, lang in ((3, 1, 0x409), (1, 0, 0)):
        names.setName(family, 1, pid, eid, lang)
        names.setName(style, 2, pid, eid, lang)
        names.setName(f"{family} {style}", 4, pid, eid, lang)
        names.setName(f"{family.replace(' ', '')}-{style.replace(' ', '')}", 6, pid, eid, lang)
    options = subset.Options()
    options.layout_features = ["kern"]
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    out = io.BytesIO()
    font.flavor = "woff2"
    font.save(out)
    return out.getvalue()


OUT.mkdir(parents=True, exist_ok=True)
swift = [
    "// Generated by scripts/update-fonts.py; do not edit.",
    "",
    "/// The handwriting fonts Dottie bundles (SIL Open Font License; see web/fonts/OFL-*.txt), as WOFF2 files.",
    "enum BundledFonts {",
    "    /// Family -> face (regular, bold, italic, boldItalic) -> base64 WOFF2.",
    "    static let faces: [String: [String: String]] = [",
]
for family, (directory, faces) in FONTS.items():
    (OUT / f"OFL-{slug(family)}.txt").write_bytes(fetch(directory, "OFL.txt"))
    sources: dict[str, bytes] = {}
    swift.append(f"        {family!r}: [".replace("'", '"'))
    for key, (file, location) in faces.items():
        if file not in sources:
            sources[file] = fetch(directory, file)
        data = face(sources[file], location, family, key)
        (OUT / f"{slug(family)}-{key}.woff2").write_bytes(data)
        swift.append(f'            "{key}": "{base64.b64encode(data).decode()}",')
        print(f"{family} {key}: {len(data) // 1024} KB")
    swift.append("        ],")
swift += ["    ]", "}", ""]
(ROOT / "Sources" / "DottieKit" / "BundledFonts.swift").write_text("\n".join(swift))
print("wrote web/fonts and Sources/DottieKit/BundledFonts.swift")
