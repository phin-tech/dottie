#!/usr/bin/env python3
"""Regenerates Sources/DottieKit/BundledModules.swift: the JavaScript libraries `require()` can always load.

Each entry is a pinned UMD build fetched from jsDelivr and embedded as a Swift string literal, so the app and a
relocated `dottie-mcp` binary need no resource bundle. Bump a version here and rerun to update.
"""
import pathlib, urllib.request

MODULES = {
    "lodash": "lodash@4.17.21/lodash.min.js",
    "d3-array": "d3-array@3.2.4/dist/d3-array.min.js",
    "d3-color": "d3-color@3.1.0/dist/d3-color.min.js",
    "d3-hierarchy": "d3-hierarchy@3.1.2/dist/d3-hierarchy.min.js",
    "dagre": "dagre@0.8.5/dist/dagre.min.js",
    "dayjs": "dayjs@1.11.13/dayjs.min.js",
}

out = pathlib.Path(__file__).resolve().parent.parent / "Sources/DottieKit/BundledModules.swift"
lines = [
    "// Generated by scripts/update-script-modules.py; do not edit.",
    "",
    "/// Libraries every script can `require()` without installing anything. A file of the same name in the",
    "/// modules folder takes precedence.",
    "enum BundledModules {",
    "    static let sources: [String: String] = [",
]
for name, path in MODULES.items():
    with urllib.request.urlopen(f"https://cdn.jsdelivr.net/npm/{path}") as r:
        src = r.read().decode("utf-8")
    hashes = "#" * 6
    assert f'"{hashes}' not in src and f"\\{hashes}" not in src
    # Swift rejects raw control characters in source; spell them as escapes (same string at run time).
    src = "".join(f"\\{hashes}u{{{ord(c):x}}}" if (ord(c) < 32 and c not in "\n\t") or ord(c) == 127 else c for c in src)
    lines.append(f'        "{name}": {hashes}"""')
    lines.append(src.rstrip("\n"))
    lines.append(f'"""{hashes},')
lines += ["    ]", "}", ""]
out.write_text("\n".join(lines))
print(f"wrote {out} ({out.stat().st_size} bytes)")
